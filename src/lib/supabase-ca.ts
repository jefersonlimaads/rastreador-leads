/**
 * Monta a conexão do pg com verificação de certificado de verdade.
 *
 * O sslmode na URL tem precedência sobre o objeto ssl no pg, e sslmode=require
 * hoje significa "verifique contra as autoridades públicas" — o que rejeita a
 * cadeia do Supabase. Por isso tiramos o parâmetro e passamos o certificado
 * raiz deles explicitamente.
 */
export function conexaoPg(url: string | undefined) {
  if (!url) return { connectionString: url };
  if (!url.includes("supabase.")) return { connectionString: url };

  return {
    connectionString: url.replace(/([?&])sslmode=[^&]*&?/g, "$1").replace(/[?&]$/, ""),
    ssl: { ca: SUPABASE_CA, rejectUnauthorized: true },
  };
}
